// Builds native/doorstop.c for every platform is_executor supports and writes
// lib/src/doorstop_bytes.g.dart, which carries the binaries as bytes.
//
//   dart run tool/build_doorstop.dart           write the file
//   dart run tool/build_doorstop.dart --check   exit 1 if it would change
//
// zig cross-compiles all four from any host. Each build writes a file named
// `doorstop`: the macOS linker's ad-hoc signature names the output file, so
// the same name is what makes two builds the same bytes.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

/// The zig release the committed bytes were built with. A different zig can
/// build different bytes, so --check refuses any other.
const zigVersion = '0.15.2';

/// Each platform, as a zig target and as the name of its `Abi` constant.
const targets = [
  (zig: 'x86_64-linux-musl', abi: 'linuxX64'),
  (zig: 'aarch64-linux-musl', abi: 'linuxArm64'),
  (zig: 'x86_64-macos', abi: 'macosX64'),
  (zig: 'aarch64-macos', abi: 'macosArm64'),
];

const source = 'native/doorstop.c';
const output = 'lib/src/doorstop_bytes.g.dart';

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final version = (await _run('zig', ['version'])).trim();
  if (version != zigVersion) {
    stderr.writeln('zig $version found; the bytes are built with $zigVersion');
    exit(2);
  }
  final out = StringBuffer()
    ..writeln('// Generated by tool/build_doorstop.dart from $source with')
    ..writeln(
      '// zig $zigVersion. Do not edit: CI rebuilds it and fails on any',
    )
    ..writeln('// difference.')
    ..writeln("import 'dart:ffi' show Abi;")
    ..writeln()
    ..writeln('/// The doorstop built for each platform: the sha256 of its')
    ..writeln('/// bytes, and the bytes in base64.')
    ..writeln(
      'const doorstopBuilds = <Abi, ({String sha256, String base64})>{',
    );
  final scratch = await Directory.systemTemp.createTemp('doorstop_build_');
  try {
    for (final t in targets) {
      final dir = await Directory('${scratch.path}/${t.zig}').create();
      final exe = '${dir.path}/doorstop';
      await _run('zig', [
        'cc',
        '-target',
        t.zig,
        '-Os',
        '-s',
        '-Wall',
        '-Wextra',
        '-Werror',
        '-o',
        exe,
        source,
      ]);
      final bytes = await File(exe).readAsBytes();
      out
        ..writeln('  Abi.${t.abi}: (')
        ..writeln("    sha256: '${sha256.convert(bytes)}',")
        ..writeln("    base64: '${base64.encode(bytes)}',")
        ..writeln('  ),');
      stdout.writeln('${t.zig}: ${bytes.length} bytes');
    }
  } finally {
    await scratch.delete(recursive: true);
  }
  out.writeln('};');
  final file = File(output);
  final now = out.toString();
  if (check) {
    final was = file.existsSync() ? file.readAsStringSync() : '';
    if (was != now) {
      stderr.writeln(
        '$output is not what $source builds: run '
        'dart run tool/build_doorstop.dart and commit it',
      );
      exit(1);
    }
    stdout.writeln('$output matches $source');
    return;
  }
  await file.writeAsString(now);
  stdout.writeln('wrote $output');
}

Future<String> _run(String exe, List<String> args) async {
  final r = await Process.run(exe, args);
  if (r.exitCode != 0) {
    stderr.writeln(
      '$exe ${args.join(' ')} failed (${r.exitCode}):\n'
      '${r.stdout}${r.stderr}',
    );
    exit(2);
  }
  return r.stdout as String; // cast-ok: Process.run decodes stdout to a String
}
